using Beacon.Core.Data;

namespace Beacon.Core.SecurityAudit;

/// <summary>
/// Writes security audit events. An event that records a change joins the change's unit of work (one
/// <c>SaveChangesAsync</c> per handler, §5.7): <see cref="StageAsync"/> adds it to the caller's context, so it commits and
/// rolls back with the change; <see cref="SaveWithEventsAsync{T}"/> does the same for events that need what the save
/// produces (a generated id, the rows an update touched). An event without a unit of work to join (a sign-in, a refusal, a
/// read of the trail) is written on its own by <see cref="RecordAsync"/>, which never fails the action it records: a
/// write failure is logged at Error with the event's fields (<see cref="SecurityAuditLogEvents.WriteFailed"/>) and counted. The actor is the
/// request's caller (<c>IBeaconActorAccessor</c>) unless the entry names another. Scoped; registered by
/// <c>AddBeaconServices</c> with <c>TryAdd</c>.
/// </summary>
public interface ISecurityAuditRecorder
{
    /// <summary>Adds <paramref name="entry"/> to <paramref name="context"/>: the caller's next save writes it, in its transaction.</summary>
    Task StageAsync(BeaconContext context, SecurityAuditEntry entry, CancellationToken cancellationToken);

    /// <summary>
    /// Saves <paramref name="context"/>'s pending changes, then the events <paramref name="events"/> builds from them (ids are
    /// generated by then), in one transaction: the caller's when one is open, else one this opens through the context's
    /// execution strategy. On a retried attempt the pending changes are saved again only when the failed attempt never
    /// saved them; once a save accepted them, the retry fails with nothing committed (a host that retries on failure sees
    /// the request fail, never a change saved without its event or an event saved twice).
    /// </summary>
    Task SaveWithEventsAsync(BeaconContext context, Func<IEnumerable<SecurityAuditEntry>> events, CancellationToken cancellationToken);

    /// <summary>
    /// Runs <paramref name="change"/> (a bulk update or delete on <paramref name="context"/>, or a delegate that reads what it
    /// changes), then saves the events <paramref name="events"/> builds from its result, in one transaction: the caller's
    /// when one is open (run once; the caller's execution strategy owns retries), else one this opens through the context's
    /// execution strategy. A retried attempt clears the context's tracker and runs <paramref name="change"/> again, so the
    /// change must not depend on changes tracked before the call, and no event of the failed attempt is saved twice.
    /// </summary>
    Task<T> SaveWithEventsAsync<T>(
        BeaconContext context,
        Func<Task<T>> change,
        Func<T, IEnumerable<SecurityAuditEntry>> events,
        CancellationToken cancellationToken);

    /// <summary>
    /// Writes <paramref name="entry"/> on its own. Never throws; the write is not cancelled with the request (an aborted
    /// sign-in attempt is still recorded) but is given up after a few seconds, so a database that does not answer never
    /// holds up the action. An event that could not be written goes to the log stream instead, with every field it would
    /// have been stored with (<see cref="SecurityAuditLogEvents.WriteFailed"/>, <c>Persisted=False</c>), and is counted.
    /// </summary>
    Task RecordAsync(SecurityAuditEntry entry, CancellationToken cancellationToken);

    /// <summary>
    /// The keyed hash a caller without a Beacon user is recorded by: the same keyed hash MCP caller audit rows carry for the
    /// same tenant (or issuer) and subject, never the subject itself.
    /// </summary>
    string CallerHashOf(string tenantOrIssuer, string subject);
}
