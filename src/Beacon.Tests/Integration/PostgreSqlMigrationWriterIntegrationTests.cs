using Beacon.Connector.PostgreSql;
using Beacon.Core.DataMigration;
using FluentAssertions;
using Microsoft.Extensions.Logging.Abstractions;
using Npgsql;
using NUnit.Framework;

namespace Beacon.Tests.Integration;

/// <summary>
/// The PostgreSQL migration writer against a real server: Truncate, Insert and Upsert (composite and all-key tables), NULLs
/// for missing values and over defaults, a stage with only the written columns (no constraints, defaults or sequence use),
/// one stage per chunk, no type conversion, a duplicate key in a chunk failing, and a Truncate rolled back with the
/// transaction when a row fails. Set
/// <see cref="PostgreSqlHostDataSourceMigrationTests.AdminConnectionStringEnvVar"/>; the test works in its own schema,
/// dropped afterwards. Without it the tests are inconclusive.
/// </summary>
[TestFixture]
public class PostgreSqlMigrationWriterIntegrationTests
{
    private string? _connectionString;
    private string _schema = null!;
    private PostgreSqlMigrationBulkWriter _writer = null!;

    [SetUp]
    public async Task SetUp()
    {
        _connectionString = Environment.GetEnvironmentVariable(PostgreSqlHostDataSourceMigrationTests.AdminConnectionStringEnvVar);
        if (string.IsNullOrWhiteSpace(_connectionString))
        {
            Assert.Inconclusive($"{PostgreSqlHostDataSourceMigrationTests.AdminConnectionStringEnvVar} is not set.");
        }

        _schema = $"beacon_mw_{Guid.NewGuid():N}";
        _writer = new PostgreSqlMigrationBulkWriter(NullLogger<PostgreSqlMigrationBulkWriter>.Instance);
        await ExecuteAsync(
            $"CREATE SCHEMA \"{_schema}\"",
            $"CREATE TABLE \"{_schema}\".\"Orders\" (tenant int NOT NULL, id int NOT NULL, total numeric, note text, PRIMARY KEY (tenant, id))",
            $"CREATE TABLE \"{_schema}\".links (a int NOT NULL, b int NOT NULL, PRIMARY KEY (a, b))",
            $"CREATE TABLE \"{_schema}\".accounts (id int PRIMARY KEY, total numeric, ref int NOT NULL GENERATED BY DEFAULT AS IDENTITY)",
            $"CREATE TABLE \"{_schema}\".counters (id int PRIMARY KEY, label text DEFAULT 'dflt', seq bigserial, big bigint)",
            $"INSERT INTO \"{_schema}\".\"Orders\" VALUES (1, 1, 10, 'old'), (1, 2, 20, 'keep')",
            $"INSERT INTO \"{_schema}\".links VALUES (1, 1)",
            $"INSERT INTO \"{_schema}\".accounts (id, total) VALUES (1, 10)",
            $"INSERT INTO \"{_schema}\".counters (id, label) VALUES (1, 'first')");
    }

    [TearDown]
    public async Task TearDown()
    {
        if (string.IsNullOrWhiteSpace(_connectionString))
        {
            return;
        }

        await ExecuteAsync($"DROP SCHEMA IF EXISTS \"{_schema}\" CASCADE");
    }

    [Test]
    public async Task Truncate_ReplacesEveryRow()
    {
        await WriteAsync("Orders", async target =>
        {
            await _writer.ClearAsync(target, CancellationToken.None);
            var written = await _writer.InsertAsync(target, Rows(Order(2, 1, 5m, "new")), CancellationToken.None);
            written.Should().Be(1);
        });

        (await OrdersAsync()).Should().Equal("2|1|5|new");
    }

    [Test]
    public async Task Insert_AddsRows_WritingNullForNullsAndMissingValues()
    {
        var rows = new MigrationRows(
            ["tenant", "id", "total", "note"],
            [
                new Dictionary<string, object?> { ["tenant"] = 3, ["id"] = 1, ["total"] = null, ["note"] = "a" },
                new Dictionary<string, object?> { ["tenant"] = 3, ["id"] = 2 }
            ]);

        await WriteAsync("Orders", async target => (await _writer.InsertAsync(target, rows, CancellationToken.None)).Should().Be(2));

        (await OrdersAsync()).Should().Equal("1|1|10|old", "1|2|20|keep", "3|1|<null>|a", "3|2|<null>|<null>");
    }

    [Test]
    public async Task Upsert_UpdatesRowsWhoseCompositeKeyExists_AndInsertsTheRest()
    {
        await WriteAsync("Orders", async target =>
        {
            var written = await _writer.UpsertAsync(target, Rows(Order(1, 1, 11m, "updated"), Order(1, 3, 30m, "added")), ["tenant", "id"], CancellationToken.None);
            written.Should().Be(2);
        });

        (await OrdersAsync()).Should().Equal("1|1|11|updated", "1|2|20|keep", "1|3|30|added");
    }

    [Test]
    public async Task Upsert_IntoAnAllKeyTable_InsertsNewRows_AndLeavesExistingOnes()
    {
        var rows = new MigrationRows(
            ["a", "b"],
            [
                new Dictionary<string, object?> { ["a"] = 1, ["b"] = 1 },
                new Dictionary<string, object?> { ["a"] = 1, ["b"] = 2 }
            ]);

        // Every row processed counts, the one left as it was too.
        await WriteAsync("links", async target => (await _writer.UpsertAsync(target, rows, ["a", "b"], CancellationToken.None)).Should().Be(2));

        (await ScalarAsync($"SELECT count(*) FROM \"{_schema}\".links")).Should().Be(2L);
    }

    // The stage holds only the written columns, without their constraints: a NOT NULL column the destination fills itself
    // (here an identity) and the rows leave out does not fail the copy into the stage.
    [Test]
    public async Task Upsert_LeavingOutANotNullColumnTheTableFills_UpdatesAndInserts()
    {
        var rows = new MigrationRows(
            ["id", "total"],
            [
                new Dictionary<string, object?> { ["id"] = 1, ["total"] = 11m },
                new Dictionary<string, object?> { ["id"] = 2, ["total"] = 20m }
            ]);

        await WriteAsync("accounts", async target => (await _writer.UpsertAsync(target, rows, ["id"], CancellationToken.None)).Should().Be(2));

        (await RowsAsync($"SELECT id, total, ref IS NOT NULL FROM \"{_schema}\".accounts ORDER BY id")).Should().Equal("1|11|True", "2|20|True");
    }

    // The stage takes no defaults, so staging spends no sequence value. The upsert's own INSERT still evaluates the default
    // for every row it proposes, the one that turns into an update too (PostgreSQL's ON CONFLICT), so the new row takes 3.
    [Test]
    public async Task Upsert_SpendsNoSequenceValuesOnTheStage()
    {
        var rows = new MigrationRows(
            ["id", "label"],
            [
                new Dictionary<string, object?> { ["id"] = 1, ["label"] = "a" },
                new Dictionary<string, object?> { ["id"] = 2, ["label"] = "b" }
            ]);

        await WriteAsync("counters", async target => (await _writer.UpsertAsync(target, rows, ["id"], CancellationToken.None)).Should().Be(2));

        (await RowsAsync($"SELECT id, label, seq FROM \"{_schema}\".counters ORDER BY id")).Should().Equal("1|a|1", "2|b|3");
    }

    // A NULL, or a value the row leaves out, is written as NULL, never replaced by the column's default.
    [Test]
    public async Task Insert_WritesNull_IntoAColumnWithADefault()
    {
        var rows = new MigrationRows(
            ["id", "label"],
            [
                new Dictionary<string, object?> { ["id"] = 2, ["label"] = null },
                new Dictionary<string, object?> { ["id"] = 3 }
            ]);

        await WriteAsync("counters", async target => (await _writer.InsertAsync(target, rows, CancellationToken.None)).Should().Be(2));

        (await RowsAsync($"SELECT id, label FROM \"{_schema}\".counters ORDER BY id")).Should().Equal("1|first", "2|<null>", "3|<null>");
    }

    // Binary COPY writes each value with the type of its CLR value and converts nothing: an int into a bigint column fails
    // the write (and the run) rather than being widened.
    [Test]
    public async Task Insert_AnIntIntoABigintColumn_FailsTheWrite()
    {
        var rows = new MigrationRows(["id", "big"], [new Dictionary<string, object?> { ["id"] = 2, ["big"] = 5 }]);

        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        await using var transaction = await connection.BeginTransactionAsync();
        var target = new MigrationWriteTarget(connection, transaction, _schema, "counters", 30);

        var write = () => _writer.InsertAsync(target, rows, CancellationToken.None);

        await write.Should().ThrowAsync<PostgresException>();
    }

    // Each chunk is its own upsert inside the run's one transaction; a chunk's stage is gone once its rows are merged.
    [Test]
    public async Task Upsert_InTwoChunksOfOneTransaction_LeavesNoStageBehind()
    {
        await WriteAsync("Orders", async target =>
        {
            (await _writer.UpsertAsync(target, Rows(Order(1, 1, 11m, "first chunk")), ["tenant", "id"], CancellationToken.None)).Should().Be(1);
            (await StagesAsync(target)).Should().Be(0L);
            (await _writer.UpsertAsync(target, Rows(Order(1, 2, 21m, "second chunk"), Order(1, 3, 30m, "added")), ["tenant", "id"], CancellationToken.None)).Should().Be(2);
            (await StagesAsync(target)).Should().Be(0L);
        });

        (await OrdersAsync()).Should().Equal("1|1|11|first chunk", "1|2|21|second chunk", "1|3|30|added");
    }

    // Two rows with the same key in one chunk fail the upsert; the run rolls back and the table is unchanged.
    [Test]
    public async Task Upsert_WithADuplicateKeyInOneChunk_Fails_AndIsRolledBack()
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        await using var transaction = await connection.BeginTransactionAsync();
        var target = new MigrationWriteTarget(connection, transaction, _schema, "Orders", 30);

        var upsert = () => _writer.UpsertAsync(target, Rows(Order(1, 1, 1m, "one"), Order(1, 1, 2m, "two")), ["tenant", "id"], CancellationToken.None);

        (await upsert.Should().ThrowAsync<PostgresException>()).Which.SqlState.Should().Be(PostgresErrorCodes.CardinalityViolation);
        await transaction.RollbackAsync();
        (await OrdersAsync()).Should().Equal("1|1|10|old", "1|2|20|keep");
    }

    // A failed write rolls the whole run back: the truncate is undone with it.
    [Test]
    public async Task ATruncate_IsRolledBack_WhenARowFails()
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        await using var transaction = await connection.BeginTransactionAsync();
        var target = new MigrationWriteTarget(connection, transaction, _schema, "Orders", 30);

        await _writer.ClearAsync(target, CancellationToken.None);
        var failing = () => _writer.InsertAsync(target, Rows(Order(5, 1, 1m, "ok"), Order(5, 1, 2m, "duplicate key")), CancellationToken.None);
        await failing.Should().ThrowAsync<PostgresException>();
        await transaction.RollbackAsync();

        (await OrdersAsync()).Should().Equal("1|1|10|old", "1|2|20|keep");
    }

    private async Task WriteAsync(string table, Func<MigrationWriteTarget, Task> write)
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        await using var transaction = await connection.BeginTransactionAsync();

        await write(new MigrationWriteTarget(connection, transaction, _schema, table, 30));
        await transaction.CommitAsync();
    }

    private static MigrationRows Rows(params Dictionary<string, object?>[] rows) => new(["tenant", "id", "total", "note"], rows);

    private static Dictionary<string, object?> Order(int tenant, int id, decimal total, string note) =>
        new() { ["tenant"] = tenant, ["id"] = id, ["total"] = total, ["note"] = note };

    // The staging tables left in the target connection's own temporary schema.
    private static async Task<object?> StagesAsync(MigrationWriteTarget target)
    {
        await using var command = new NpgsqlCommand(
            "SELECT count(*) FROM pg_class WHERE relnamespace = pg_my_temp_schema() AND relname LIKE 'beacon\\_stage\\_%'",
            (NpgsqlConnection)target.Connection,
            (NpgsqlTransaction)target.Transaction);

        return await command.ExecuteScalarAsync();
    }

    private Task<List<string>> OrdersAsync() => RowsAsync($"SELECT tenant, id, total, note FROM \"{_schema}\".\"Orders\" ORDER BY tenant, id");

    private async Task<List<string>> RowsAsync(string sql)
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        await using var reader = await command.ExecuteReaderAsync();
        var rows = new List<string>();
        while (await reader.ReadAsync())
        {
            var values = Enumerable.Range(0, reader.FieldCount)
                .Select(x => reader.IsDBNull(x) ? "<null>" : Convert.ToString(reader.GetValue(x), System.Globalization.CultureInfo.InvariantCulture));
            rows.Add(string.Join("|", values));
        }

        return rows;
    }

    private async Task<object?> ScalarAsync(string sql)
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);

        return await command.ExecuteScalarAsync();
    }

    private async Task ExecuteAsync(params string[] statements)
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        foreach (var statement in statements)
        {
            await using var command = new NpgsqlCommand(statement, connection);
            await command.ExecuteNonQueryAsync();
        }
    }
}
