    [Test]
    public async Task BuildAgentsMd_OrdersTablesByDescriptionThenRelations_AndScopesToTheProject()
    {
        var store = new DocsStore();
        var dataSource = new DataSource
        {
            Id = 1,
            Name = "NetgiroContext",
            DataSourceType = DataSourceType.Database,
            DatabaseEngineType = DatabaseEngineType.MSSQL,
            EncryptedConnectionData = "enc",
            IsReadOnly = true,
            HostManagedKey = "efcore:NetgiroContext"
        };
        store.Projects.Add(new Project { Id = ProjectId, Name = "Netgiro", Description = "Financing." });
        store.ListFor<ProjectDataSource>().Add(new ProjectDataSource { ProjectId = ProjectId, DataSourceId = 1, DataSource = dataSource });

        var plain = Table(10, dataSource, "Audit", null);
        var related = Table(11, dataSource, "Claims", null);
        related.Columns.Add(Column(related, "LoanId", null, isForeignKey: true));
        var described = Table(12, dataSource, "Loans", "Loans.");
        var customers = Table(13, dataSource, "Customers", null);
        customers.Columns.Add(Column(customers, "Email", "Mail " + HostModelReader.MaskedDescriptionMarker));
        store.ListFor<DatabaseMetadata>().AddRange([plain, related, described, customers]);
        store.ListFor<ColumnMetadata>().AddRange(store.ListFor<DatabaseMetadata>().SelectMany(x => x.Columns));

        store.ListFor<McpGlossaryTerm>().Add(new McpGlossaryTerm { Id = 1, ProjectId = ProjectId, Term = "Loan", Definition = "Money lent." });
        store.ListFor<McpGlossaryTerm>().Add(new McpGlossaryTerm { Id = 2, ProjectId = ProjectId, Term = "Inactive", Definition = "x", IsActive = false });
        store.ListFor<McpGlossaryTerm>().Add(new McpGlossaryTerm { Id = 3, ProjectId = 99, Term = "Foreign", Definition = "Other project." });
        store.Documents.Add(new ProjectImportedDocument { Id = 1, ProjectId = ProjectId, SourceKey = "k", Path = "README.md", Title = "Readme", ContentHash = "h", Content = "c" });
        store.Documents.Add(new ProjectImportedDocument { Id = 2, ProjectId = 99, SourceKey = "k", Path = "other.md", Title = "Other", ContentHash = "h", Content = "c" });

        var service = new ProjectBriefService(store.Factory().Object);

        var brief = await service.BuildAgentsMdAsync(ProjectId, CancellationToken.None);
        var again = await service.BuildAgentsMdAsync(ProjectId, CancellationToken.None);

        brief.Should().Be(again, "the brief is deterministic");
        brief!.IndexOf("`dbo.Loans`", StringComparison.Ordinal).Should().BeLessThan(brief.IndexOf("`dbo.Customers`", StringComparison.Ordinal));
        brief.IndexOf("`dbo.Customers`", StringComparison.Ordinal).Should().BeLessThan(brief.IndexOf("`dbo.Claims`", StringComparison.Ordinal));
        brief.IndexOf("`dbo.Claims`", StringComparison.Ordinal).Should().BeLessThan(brief.IndexOf("`dbo.Audit`", StringComparison.Ordinal));
        brief.Should().Contain("| NetgiroContext | MSSQL | 4 | host-managed, read-only");
        brief.Should().Contain("- `dbo.Customers.Email`");
        brief.Should().Contain("- **Loan** — Money lent.");
        brief.Should().NotContain("Inactive").And.NotContain("Foreign").And.NotContain("other.md");
        brief.Should().Contain("- Readme — `README.md`");
    }

